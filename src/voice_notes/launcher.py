"""Double-clickable "Voice Notes.app" that opens the web interface, starting the server if needed.

`voice-notes launcher install` writes a minimal app bundle whose executable is a shell script. The
script runs `voice-notes launcher open` with this checkout's Python, then exits; the server it starts
keeps running in the background (or the launchd service, if installed, is simply reused). Settings come
from ~/.voice-notes-config.json on every launch, so the app never needs reinstalling after `configure`.
"""
import json
import os
import platform
import plistlib
import shlex
import shutil
import subprocess
import sys
import time
import urllib.error
import urllib.request
import webbrowser
from pathlib import Path

from .session import atomic_write

APP_NAME = "Voice Notes"
BUNDLE_ID = "local.voice-notes.launcher"
EXECUTABLE = "voice-notes-launcher"
START_TIMEOUT = 60.0  # seconds for a cold server start (first build of the frontend is not needed)


def default_destination() -> Path:
    return Path.home() / "Applications"


def logs_dir() -> Path:
    return Path.home() / "Library" / "Logs" / "voice-notes"


def app_script(*, python: str, source_root: Path, working_dir: Path, build_dir: Path, config_file: str | None) -> str:
    log = logs_dir() / "launcher.log"
    exports = [f"PYTHONPATH={shlex.quote(str(source_root))}", "PYTHONUNBUFFERED=1"]
    if config_file:
        exports.append(f"VOICE_NOTES_CONFIG={shlex.quote(config_file)}")
    return f"""#!/bin/sh
# Generated by `voice-notes launcher install`. Reinstall it after moving the checkout.
mkdir -p {shlex.quote(str(log.parent))}
exec >>{shlex.quote(str(log))} 2>&1
echo "--- $(date) Voice Notes launcher"
cd {shlex.quote(str(working_dir))} || exit 1
export {' '.join(exports)}
if ! {shlex.quote(python)} -m voice_notes.cli --build-dir {shlex.quote(str(build_dir))} launcher open; then
  /usr/bin/osascript -e 'display alert "Voice Notes could not start" message "Details are in {log}"' >/dev/null
  exit 1
fi
"""


def info_plist() -> dict:
    return {
        "CFBundleName": APP_NAME,
        "CFBundleDisplayName": APP_NAME,
        "CFBundleIdentifier": BUNDLE_ID,
        "CFBundleExecutable": EXECUTABLE,
        "CFBundlePackageType": "APPL",
        "CFBundleVersion": "1",
        "CFBundleShortVersionString": "1.0",
        "LSMinimumSystemVersion": "26.0",
        # No Dock icon: the script opens the browser and exits within seconds.
        "LSUIElement": True,
        "NSMicrophoneUsageDescription": "Voice Notes transcribes your meetings on this Mac.",
        "NSAudioCaptureUsageDescription": "Voice Notes transcribes the other side of your meetings on this Mac.",
    }


def install(destination: Path, *, build_dir: Path, working_dir: Path | None = None) -> Path:
    from .config import CONFIG_ENV, config_path
    app = Path(destination).expanduser() / f"{APP_NAME}.app"
    contents = app / "Contents"
    (contents / "MacOS").mkdir(parents=True, exist_ok=True)
    (contents / "Resources").mkdir(exist_ok=True)
    (contents / "Info.plist").write_bytes(plistlib.dumps(info_plist()))
    script = contents / "MacOS" / EXECUTABLE
    atomic_write(script, app_script(
        python=sys.executable, source_root=Path(__file__).resolve().parents[1],
        working_dir=(working_dir or Path.cwd()).resolve(), build_dir=Path(build_dir).resolve(),
        config_file=str(config_path().resolve()) if os.environ.get(CONFIG_ENV) else None))
    script.chmod(0o755)
    if platform.system() == "Darwin":
        # Tell Finder and Spotlight about the new or updated bundle; harmless if it fails.
        subprocess.run(["/usr/bin/touch", str(app)], check=False)
    return app


def uninstall(destination: Path) -> Path | None:
    app = Path(destination).expanduser() / f"{APP_NAME}.app"
    if not (app / "Contents" / "MacOS" / EXECUTABLE).is_file():
        return None  # never delete a bundle this command did not create
    shutil.rmtree(app)
    return app


def running(port: int, timeout: float = 1.0) -> bool:
    """True when a Voice Notes server answers on this port."""
    try:
        with urllib.request.urlopen(f"http://127.0.0.1:{port}/api/settings", timeout=timeout) as response:
            settings = json.loads(response.read())
    except (OSError, ValueError, urllib.error.URLError):
        return False
    return isinstance(settings, dict) and "segment_minutes" in settings


def open_browser(url: str):
    if platform.system() == "Darwin":
        subprocess.run(["/usr/bin/open", url], check=False)
    else:
        webbrowser.open(url)


def open_ui(*, port: int, data_dir: Path, build_dir: Path, speakers_dir: Path,
            timeout: float = START_TIMEOUT, command: list[str] | None = None) -> str:
    """Open the web interface, starting `voice-notes serve` in the background if nothing answers."""
    url = f"http://localhost:{port}/"
    if running(port):
        print(f"Voice Notes is already running: {url}")
        open_browser(url)
        return url
    log = logs_dir() / "server.launcher.log"
    log.parent.mkdir(parents=True, exist_ok=True)
    command = command or [sys.executable, "-m", "voice_notes.cli", "--build-dir", str(Path(build_dir).resolve()),
                          "--speakers-dir", str(Path(speakers_dir).resolve()),
                          "serve", "--port", str(port), "--data-dir", str(Path(data_dir).resolve())]
    with log.open("a") as output:
        output.write(f"--- {time.strftime('%Y-%m-%d %H:%M:%S')} starting: {shlex.join(command)}\n")
        output.flush()
        process = subprocess.Popen(command, stdin=subprocess.DEVNULL, stdout=output, stderr=subprocess.STDOUT,
                                   start_new_session=True)  # keeps running after the launcher exits
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        if process.poll() is not None:
            tail = "".join(log.read_text(errors="replace").splitlines(keepends=True)[-15:])
            raise RuntimeError(f"The server exited with status {process.returncode}. Log: {log}\n{tail}")
        if running(port, timeout=0.5):
            print(f"Started Voice Notes: {url} (server log: {log})")
            open_browser(url)
            return url
        time.sleep(0.3)
    raise RuntimeError(f"The server did not answer on port {port} within {timeout:g} seconds. Log: {log}")


def main(args) -> int:
    if args.action == "open":
        open_ui(port=args.port, data_dir=args.data_dir, build_dir=args.build_dir, speakers_dir=args.speakers_dir)
    elif args.action == "install":
        if platform.system() != "Darwin":
            print("voice-notes: the app launcher is for macOS; creating the bundle anyway.", file=sys.stderr)
        app = install(args.dest, build_dir=args.build_dir)
        print(f"Created {app}\nDouble-click it (or find \"{APP_NAME}\" in Spotlight) to open the web interface; "
              "it starts the server when it is not already running.\n"
              f"Launcher log: {logs_dir() / 'launcher.log'}\n"
              "Run `voice-notes launcher install` again if you move this checkout.")
    else:
        app = uninstall(args.dest)
        print(f"Removed {app}" if app else f"No {APP_NAME}.app made by voice-notes in {Path(args.dest).expanduser()}")
    return 0
